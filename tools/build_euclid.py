#!/usr/bin/env python3
"""Convert pinned IRSA NUNIQ FITS MOCs to lossless order-13 ranges.
Requires astropy. No network access; originals and hashes live in data/euclid.
"""
import hashlib
import json
from pathlib import Path
from astropy.io import fits

ROOT = Path(__file__).resolve().parents[1]
result = {}
for kind in ('wide', 'deep'):
    path = ROOT / 'data/euclid' / f'euclid_dr1_{kind}.moc.fits'
    with fits.open(path) as hdus:
        h = hdus[1].header
        assert h['ORDERING'] == 'NUNIQ' and h['COORDSYS'] == 'C'
        order = h['MOCORDER']
        assert order == 13
        ranges = []
        for value in hdus[1].data['PIXEL']:
            uniq = int(value)
            depth = (uniq.bit_length() - 3) // 2
            pixel = uniq - 4 * 4 ** depth
            assert 0 <= depth <= order and 0 <= pixel < 12 * 4 ** depth
            scale = 4 ** (order - depth)
            ranges.append((pixel * scale, (pixel + 1) * scale))
    merged = []
    for start, end in sorted(ranges):
        if merged and start <= merged[-1][1]:
            merged[-1][1] = max(end, merged[-1][1])
        else:
            merged.append([start, end])
    assert sum(b-a for a,b in merged) == sum(b-a for a,b in ranges), 'Unexpected overlapping source cells'
    result[kind] = dict(order=order, ranges=[n for pair in merged for n in pair],
        areaSqDeg=sum(b-a for a,b in merged) / (12 * 4**order) * 41252.96124941927,
        sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
        url=f'https://nasa-irsa-euclid-dr1.s3.amazonaws.com/dr1/MOC/euclid_dr1_{kind}.moc.moc.fits')
    print(kind, len(merged), 'ranges;', result[kind]['areaSqDeg'], 'sq deg')
(ROOT / 'src/euclid-data.js').write_text('// Generated by tools/build_euclid.py; exact MOC ranges, not a planned survey.\nconst EUCLID = ' + json.dumps(result, separators=(',', ':')) + ';\n')
